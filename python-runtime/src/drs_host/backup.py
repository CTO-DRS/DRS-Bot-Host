"""Fleet backup & restore (v1.4).

``create_backup`` bundles every installed bot folder (source files +
``bot.json``) into one zip under ``<data_dir>/backups/``:

    drs-backup-<stamp>.zip
    ├── backup.json          ← metadata (host version, bot list, counts)
    └── bots/<id>/...        ← each bot's files, exactly as installed

Deliberately excluded (kept small and re-creatable):

- ``logs/`` — runtime JSONL logs (use ``export_logs`` for those)
- ``__pycache__`` / ``*.pyc`` — regenerated by the interpreter
- pip site-dirs — they live outside ``bots/`` and are re-installable via
  ``install_bot_requirements``

``restore_backup`` requires the ``backup.json`` metadata (so a random zip
cannot be smuggled in as a "backup"), then re-imports every bot folder
through ``Supervisor.import_folder`` — the full hardened pipeline
(manifest validation, extension whitelist, size limits, overwrite guard).

Everything is stdlib-only and works identically on desktop and Chaquopy.
"""

from __future__ import annotations

import json
import shutil
import sys
import tempfile
import time
import zipfile
from pathlib import Path, PurePosixPath

from . import __version__, importer

METADATA_NAME = "backup.json"
BOTS_PREFIX = "bots/"
EXCLUDED_DIR_NAMES = {"__pycache__", ".git", ".svn", ".idea", "__MACOSX", "logs"}


def _member_ok(name: str) -> bool:
    """Same traversal rules as the importer (kept in sync deliberately)."""
    if not name:
        return False
    if name.startswith("/") or "\\" in name:
        return False
    first = name.split("/", 1)[0]
    if ":" in first:
        return False
    if any(part == ".." for part in PurePosixPath(name).parts):
        return False
    return True


def _included(path: Path, bot_dir: Path) -> bool:
    relative = path.relative_to(bot_dir)
    return not (set(relative.parts) & EXCLUDED_DIR_NAMES) and path.suffix.lower() != ".pyc"


def create_backup(supervisor, dest=None) -> dict:
    """Zip every installed bot + metadata into ``dest`` (or a default path).

    Returns ``{"ok": True, "path": ..., "bots": [...], "bytes": n}`` or the
    standard rejection shape. Running bots are included (files on disk are
    stable; runtime *state* is not part of a backup).
    """
    with supervisor.lock:
        bots = list(supervisor.bots.values())
    if not bots:
        return {"ok": False, "errors": ["no bots installed — nothing to back up"]}
    backups_dir = Path(dest) if dest else (supervisor.bots_root.parent / "backups")
    backups_dir.mkdir(parents=True, exist_ok=True)
    stamp = time.strftime("%Y%m%d-%H%M%S", time.gmtime())
    path = backups_dir / f"drs-backup-{stamp}.zip"

    bot_records = []
    try:
        with zipfile.ZipFile(path, "w", compression=zipfile.ZIP_DEFLATED) as archive:
            for bot in sorted(bots, key=lambda b: b.manifest.id):
                files = [
                    item
                    for item in sorted(bot.bot_dir.rglob("*"))
                    if item.is_file() and _included(item, bot.bot_dir)
                ]
                for item in files:
                    archive.write(
                        item,
                        arcname=f"{BOTS_PREFIX}{bot.manifest.id}/{item.relative_to(bot.bot_dir).as_posix()}",
                    )
                bot_records.append(
                    {
                        "id": bot.manifest.id,
                        "name": bot.manifest.name,
                        "version": bot.manifest.version,
                        "files": len(files),
                    }
                )
            metadata = {
                "kind": "drs-bot-host-backup",
                "backup_version": 1,
                "created_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
                "drs_host": __version__,
                "python": sys.version.split()[0],
                "bot_count": len(bot_records),
                "bots": bot_records,
            }
            archive.writestr(METADATA_NAME, json.dumps(metadata, ensure_ascii=False, indent=2))
    except Exception as exc:  # noqa: BLE001 - partial archive must not linger
        path.unlink(missing_ok=True)
        return {"ok": False, "errors": [f"backup failed: {exc}"]}
    return {
        "ok": True,
        "path": str(path),
        "bots": [record["id"] for record in bot_records],
        "bot_count": len(bot_records),
        "bytes": path.stat().st_size,
    }


def _read_metadata(archive: zipfile.ZipFile):
    try:
        raw = archive.read(METADATA_NAME)
    except KeyError:
        return None, [f"{METADATA_NAME} missing — not a DRS Bot Host backup"]
    try:
        document = json.loads(raw.decode("utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        return None, [f"{METADATA_NAME} is not valid JSON: {exc}"]
    if not isinstance(document, dict) or document.get("kind") != "drs-bot-host-backup":
        return None, [f"{METADATA_NAME} is not a DRS Bot Host backup manifest"]
    if not isinstance(document.get("bots"), list):
        return None, [f"{METADATA_NAME} has no bot list"]
    return document, []


def restore_backup(supervisor, zip_path, *, overwrite: bool = False) -> dict:
    """Re-import every bot from a backup zip created by ``create_backup``.

    Each ``bots/<id>/`` folder is extracted to a temp dir and handed to
    ``Supervisor.import_folder`` (full manifest + file validation).
    """
    zpath = Path(zip_path)
    if not zpath.is_file():
        return {"ok": False, "errors": [f"backup file not found: {zpath}"]}
    try:
        with zipfile.ZipFile(zpath) as archive:
            names = archive.namelist()
            unsafe = [n for n in names if not _member_ok(n)]
            if unsafe:
                return {"ok": False, "errors": ["unsafe path(s) in backup: " + ", ".join(unsafe[:5])]}
            metadata, errors = _read_metadata(archive)
            if metadata is None:
                return {"ok": False, "errors": errors}

            bot_dirs = {}
            for name in names:
                if name.endswith("/"):
                    continue
                if not name.startswith(BOTS_PREFIX):
                    continue
                remainder = name[len(BOTS_PREFIX):]
                if not remainder:
                    continue
                parts = PurePosixPath(remainder).parts
                if not parts or parts[0] in EXCLUDED_DIR_NAMES:
                    continue
                bot_dirs.setdefault(parts[0], []).append(name)

            if not bot_dirs:
                return {"ok": False, "errors": ["backup contains no bot folders"]}

            restored, failures = [], []
            tmp_root = Path(tempfile.mkdtemp(prefix="drs-restore-"))
            try:
                for bot_id in sorted(bot_dirs):
                    extract_dir = tmp_root / bot_id
                    extract_dir.mkdir(parents=True, exist_ok=True)
                    for name in bot_dirs[bot_id]:
                        relative = PurePosixPath(name[len(BOTS_PREFIX) + len(bot_id) + 1:])
                        target = extract_dir.joinpath(*relative.parts)
                        target.parent.mkdir(parents=True, exist_ok=True)
                        with archive.open(name) as src, open(target, "wb") as out:
                            shutil.copyfileobj(src, out)
                    result = supervisor.import_folder(extract_dir, overwrite=overwrite)
                    if result.get("ok"):
                        restored.append(result["bot_id"])
                    else:
                        failures.append(
                            {"bot": bot_id, "errors": result.get("errors", ["import failed"])}
                        )
            finally:
                shutil.rmtree(tmp_root, ignore_errors=True)
    except zipfile.BadZipFile:
        return {"ok": False, "errors": ["not a valid zip archive"]}

    if not restored:
        return {
            "ok": False,
            "errors": ["no bot could be restored"],
            "failures": failures,
        }
    response = {
        "ok": True,
        "restored": restored,
        "count": len(restored),
        "backup_created_at": metadata.get("created_at"),
        "backup_drs_host": metadata.get("drs_host"),
    }
    if failures:
        response["failures"] = failures
        response["warning"] = f"{len(failures)} bot(s) in the backup could not be restored"
    return response


__all__ = ["create_backup", "restore_backup", "METADATA_NAME", "BOTS_PREFIX"]
