"""Generate ready-to-import sample bots from a template.

``drs_host.scaffold.scaffold_bot("My Bot", dest)`` creates
``<dest>/<slug>/`` containing a valid ``bot.json``, a working ``main.py``
built on the public SDK, and a README — instantly importable by the
supervisor (or the app's Import tab) with zero editing.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

from .manifest import _ID_RE, validate_manifest

SCAFFOLD_MANIFEST = {
    "spec_version": 1,
    "id": "SLUG",
    "name": "NAME",
    "version": "0.1.0",
    "entrypoint": "main.py",
    "language": "python",
    "author": "drs_host scaffold",
    "description": "NAME — generated by drs_host scaffold",
    "requirements": [],
    "config": {
        "interval_seconds": 5.0,
        "message": "hello from NAME",
    },
    "restart": {
        "policy": "on_failure",
        "max_restarts": 3,
    },
    "auto_start": False,
}

SCAFFOLD_MAIN = '''\
"""NAME — scaffolded by DRS Bot Host.

A cooperative heartbeat bot: it logs ``message`` every ``interval_seconds``
until the host asks it to stop. Edit freely, re-zip, re-import.
"""

from drs_host.sdk import get_context


def main():
    ctx = get_context()
    if ctx is None:
        print("no host context; run this bot inside DRS Bot Host")
        return

    interval = float(ctx.config.get("interval_seconds", 5) or 5)
    message = str(ctx.config.get("message", "hello"))
    if interval <= 0:
        interval = 5.0

    ctx.logger.info(f"started; interval={interval:.2f}s")
    counter = 0
    while not ctx.should_stop:
        ctx.logger.info(f"[{counter}] {message}")
        counter += 1
        ctx.sleep_or_stop(interval)
    ctx.logger.info(f"stopped cleanly after {counter} ticks")


main()
'''

SCAFFOLD_README = """\
# NAME

Scaffolded by `drs_host scaffold` (DRS Bot Host).

- `bot.json` — manifest: identity, restart policy, `config` values
- `main.py`  — entrypoint built on the public `drs_host.sdk` API

Tune `config.interval_seconds` / `config.message` in `bot.json` (or from the
app via `set_bot_config`) — changes apply on the next start.
"""


def slugify(name: str) -> str:
    """Derive a manifest-legal bot id from a free-form display name."""
    slug = re.sub(r"[^a-z0-9]+", "-", name.strip().lower()).strip("-")
    return slug


def scaffold_bot(name: str, dest) -> dict:
    """Create ``<dest>/<slug>/`` with a valid, runnable bot. Never raises."""
    clean = (name or "").strip()
    if not clean:
        return {"ok": False, "errors": ["bot name is required"]}

    slug = slugify(clean)
    if not _ID_RE.match(slug):
        return {
            "ok": False,
            "errors": [
                f"cannot derive a valid bot id from {clean!r} "
                f"(got {slug!r}; need 2-64 chars of [a-z0-9-_])"
            ],
        }

    target_root = Path(dest)
    target = target_root / slug
    if target.exists():
        return {"ok": False, "errors": [f"target already exists: {target}"]}

    manifest = json.loads(
        json.dumps(SCAFFOLD_MANIFEST)
    )  # deep copy of the template
    manifest["id"] = slug
    manifest["name"] = clean
    manifest["description"] = f"{clean} — generated by drs_host scaffold"
    manifest["config"] = dict(manifest["config"])
    manifest["config"]["message"] = f"hello from {clean}"

    # Guarantee the generated document passes the strict manifest validator
    # *before* anything touches the disk.
    validated, errors = validate_manifest(manifest)
    if validated is None:
        return {"ok": False, "errors": errors}

    main_py = SCAFFOLD_MAIN.replace("NAME", clean)
    readme = SCAFFOLD_README.replace("NAME", clean)

    target.mkdir(parents=True, exist_ok=False)
    written = []
    try:
        (target / "bot.json").write_text(
            json.dumps(manifest, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
        )
        written.append("bot.json")
        (target / "main.py").write_text(main_py, encoding="utf-8")
        written.append("main.py")
        (target / "README.md").write_text(readme, encoding="utf-8")
        written.append("README.md")
    except OSError as exc:
        return {"ok": False, "errors": [f"write failed: {exc}"], "files": written}

    return {
        "ok": True,
        "id": slug,
        "path": str(target),
        "files": written,
    }
